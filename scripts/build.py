def public_metadata(info):
    info.uid = info.gid = 0
    info.uname = info.gname = ''
    info.mtime = 0
    info.pax_headers = {}
    return info

"""Build without npm dependencies. Source order is intentional and tested."""
from pathlib import Path
import json, tarfile
root = Path(__file__).resolve().parents[1]
order = ('tokens', 'base', 'sidebar', 'list', 'editor', 'settings', 'picker', 'goto', 'notifications', 'icons', 'responsive')
css = '/* Generated by scripts/build.py. Edit src/*.css, not this file. */\n\n' + '\n'.join((root / 'src' / (name + '.css')).read_text() for name in order)
(root / 'plugin/userchrome.css').write_text(css)
for name in ('userchrome.css', 'userstyle.css'):
    (root / name).write_bytes((root / 'plugin' / name).read_bytes())
version = json.loads((root / 'plugin/manifest.json').read_text())['version']
with tarfile.open(root / f'io.local.calm.mac.theme-{version}.jpl', 'w:gz') as archive:
    for name in ('manifest.json', 'index.js', 'userchrome.css', 'userstyle.css'):
        archive.add(root / 'plugin' / name, arcname=name, filter=public_metadata)
print(f'Built Calm Mac {version}')
